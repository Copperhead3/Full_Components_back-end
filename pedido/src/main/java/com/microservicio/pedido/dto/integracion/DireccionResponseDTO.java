package com.microservicio.pedido.dto.integracion;

public class DireccionResponseDTO {

    private Long idDireccion;
    private String region;
    private String comuna;
    private String calle;
    private String numero;
    private String deptoCasa;
    private String referencia;
    private boolean predeterminada;

    public DireccionResponseDTO() {
    }

    public Long getIdDireccion() {
        return idDireccion;
    }

    public void setIdDireccion(Long idDireccion) {
        this.idDireccion = idDireccion;
    }

    public String getRegion() {
        return region;
    }

    public void setRegion(String region) {
        this.region = region;
    }

    public String getComuna() {
        return comuna;
    }

    public void setComuna(String comuna) {
        this.comuna = comuna;
    }

    public String getCalle() {
        return calle;
    }

    public void setCalle(String calle) {
        this.calle = calle;
    }

    public String getNumero() {
        return numero;
    }

    public void setNumero(String numero) {
        this.numero = numero;
    }

    public String getDeptoCasa() {
        return deptoCasa;
    }

    public void setDeptoCasa(String deptoCasa) {
        this.deptoCasa = deptoCasa;
    }

    public String getReferencia() {
        return referencia;
    }

    public void setReferencia(String referencia) {
        this.referencia = referencia;
    }

    public boolean isPredeterminada() {
        return predeterminada;
    }

    public void setPredeterminada(boolean predeterminada) {
        this.predeterminada = predeterminada;
    }
}